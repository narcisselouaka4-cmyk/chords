import assert from 'node:assert/strict';
import fs from 'node:fs';
import {lastPlayingTake} from './take-attachment.js';
import {restoreConversationPlaying} from './personal-source.js';
import {sendCopilotMessage,myPlayingExample} from './copilot-client.js';
import {answerActions} from './copilot-tab.js';
import {buildPhraseArrangement} from './phrase-arrangement.js';
import {PROPOSAL_POLICY} from './proposal-policy.js';
import {applyTakeEdit} from './take-edit.js';
const source=JSON.parse(fs.readFileSync(new URL('./fixtures/copilot-session017.json',import.meta.url)));
const approved=JSON.parse(fs.readFileSync(new URL('./fixtures/copilot-approved-reference.json',import.meta.url)));
const old={role:'assistant',content:'Voici trois propositions.',toolResult:{originalTake:source,phraseHarmony:true,variants:[{id:'enrich',advice:{version:4},example:{events:[]}}]}};
const messages=[{role:'user',content:'Fais-moi des propositions'},old,{role:'user',content:'Propose une autre version de mon jeu.'},{role:'assistant',content:'Réponse vide',isError:true}];
const before=JSON.stringify(messages);
assert.equal(lastPlayingTake(messages),source);
const restored=restoreConversationPlaying(null,messages);assert.equal(restored.playing.passage,source);
const replay=await sendCopilotMessage({message:'Rejoue ma session.',messages,context:null});
assert(replay.autoplay);assert.deepEqual(replay.toolResult.example.events,myPlayingExample({passage:source}).example.events);
const actions=answerActions(old,{last:false});assert.equal(actions.length,1);
const update=await sendCopilotMessage({message:actions[0].message,messages,context:null});
assert(update.autoplay);assert.equal(update.toolResult.proposalPolicy,PROPOSAL_POLICY);assert.equal(update.toolResult.variants.length,1);
const first=update.toolResult.variants[0];
assert.deepEqual(first.harmony,buildPhraseArrangement(source,{message:actions[0].message}).harmony);
const changed=applyTakeEdit(source,first.advice.edit);assert(changed);
for(const event of approved.melody)assert(changed.events.some(e=>JSON.stringify(e)===JSON.stringify(event)));
const next=await sendCopilotMessage({message:'Propose une autre version de mon jeu.',messages,context:null});assert.equal(next.toolResult.proposalPolicy,PROPOSAL_POLICY);assert(next.toolResult.variants.length);
assert.equal(JSON.stringify(messages),before);
const fresh={duration:1,key:'C',events:[{type:'note_on',note:60,velocity:.7,time:0},{type:'note_off',note:60,time:.5}]};
assert.equal(lastPlayingTake([...messages,{role:'user',take:fresh}]),fresh);
assert.equal(answerActions(old,{last:false,takeSource:fresh}).length,0);
assert.equal(restoreConversationPlaying({type:'autonomous',playing:{passage:fresh}},messages).playing.passage,fresh);
const session={type:'session',events:fresh.events};assert.equal(restoreConversationPlaying(session,messages),session);
const tutorial={type:'tutorial'};assert.equal(restoreConversationPlaying(tutorial,messages),tutorial);
assert.equal(lastPlayingTake([{role:'assistant',toolResult:{example:{events:source.events}}}]),null);
console.log('✓ Historique sans prise jointe : source récupérée, rejeu exact, mise à jour vers le moteur actuel, mélodie approuvée intacte, relance locale, nouvelle prise prioritaire et archives inchangées');
