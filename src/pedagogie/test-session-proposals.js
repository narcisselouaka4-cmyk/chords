import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {personalContext} from './personal-source.js';
import {sendCopilotMessage} from './copilot-client.js';
const fixture=JSON.parse(readFileSync(new URL('./fixtures/copilot-approved-links.json',import.meta.url)));
const take=fixture.take||fixture;
const session={...take,key:'C',offset:2,events:[...take.events,{type:'control',controller:64,value:0,time:take.duration||18}]};
const before=JSON.stringify(session);
const context={type:'session',playing:{session}};
const adapted=personalContext(context).playing.passage;
assert.equal(adapted.events.find(e=>e.type==='note_on').note,session.events.find(e=>e.type==='note_on').note+2);
assert(adapted.events.some(e=>e.type==='control'&&e.controller===64));assert.equal(JSON.stringify(session),before);assert.equal(adapted.key,'D majeur');
const first=await sendCopilotMessage({message:'Enrichis mes accords',messages:[],context});
assert(first.toolResult.variants.length);assert.deepEqual(first.toolResult.originalTake.events,adapted.events);
const hear=await sendCopilotMessage({message:'Fais-moi entendre un exemple',messages:[{role:'assistant',...first}],context});
assert(hear.autoplay);assert.deepEqual(hear.toolResult.variants,first.toolResult.variants);
const other={type:'session',playing:{session:{...session,offset:-2}}};
const changed=await sendCopilotMessage({message:'Fais-moi entendre un exemple',messages:[{role:'assistant',...first}],context:other});
assert.deepEqual(changed.toolResult.originalTake.events,personalContext(other).playing.passage.events);
assert.notDeepEqual(changed.toolResult.example.events,first.toolResult.example.events);
const direct=await sendCopilotMessage({message:'Améliore mon jeu',messages:[],context:{type:'session',...session}});
assert(direct.toolResult.variants.length);
console.log('Sessions : source exacte, transposition, pédale, enrichissement, écoute, changement de session et contexte direct vérifiés.');
